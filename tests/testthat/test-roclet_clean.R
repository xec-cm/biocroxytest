test_that("roclet_clean defers file removal until output", {
  base_path <- tempfile("longtests-package-")
  on.exit(unlink(base_path, recursive = TRUE), add = TRUE)
  longtests_path <- file.path(base_path, "longtests", "testthat")
  expect_error(roclet_clean.roclet_longtests(NULL, base_path))
  dir.create(longtests_path, recursive = TRUE)
  manual <- file.path(longtests_path, "test-biocroxytest-manual.r")
  generated <- file.path(longtests_path, "test-biocroxytest-generated.r")
  writeLines("# A manual test", manual)
  writeLines("# Generated by biocroxytest: do not edit by hand!", generated)

  roclet <- longtests_roclet()
  roxygen2::roclet_clean(roclet, base_path)
  expect_true(all(file.exists(c(manual, generated))))
  roxygen2::roclet_output(roclet, list(longtests = list()), base_path)
  expect_identical(readLines(manual), "# A manual test")
  expect_false(file.exists(generated))
})
