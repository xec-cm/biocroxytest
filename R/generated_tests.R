#' List and check generated tests
#'
#' The inventory lists owned test files in `tests/testthat` and
#' `longtests/testthat`. It includes `@tests` and `@testexamples` files from
#' roxytest that biocroxytest can adopt.
#' Manual tests, helpers and snapshots are excluded.
#'
#' The check regenerates tests in a temporary copy using the package's
#' roxygen configuration and a fresh R session. It checks both suites for
#' [tests_roclet()] or only the long suite for [longtests_roclet()]. Install
#' the package's development dependencies before running the check. The
#' checkout is left in place and `.git` is excluded from the copy. Use a
#' checkout without symbolic links, junctions, or special files, apart from
#' excluded Git metadata. Roxygen loads package code, so check packages
#' whose code you trust. LF and CRLF are equivalent in generated files.
#'
#' @param path Path to the package root.
#' @return `generated_test_inventory()` returns a data frame with `suite`,
#'   `source`, and `path` columns. Paths are relative to the package root.
#'   `check_generated_tests()` returns `TRUE` invisibly if output is current.
#'   Otherwise it signals a `biocroxytest_stale_tests` error with a `changes`
#'   data frame. Its `status` column is `missing`, `changed`, or `obsolete`,
#'   followed by the inventory columns.
#' @export
#' @examples
#' pkg <- tempfile("generated-test-example-")
#' dir.create(file.path(pkg, "tests", "testthat"), recursive = TRUE)
#' writeLines("Package: examplepkg", file.path(pkg, "DESCRIPTION"))
#' writeLines(
#'   "# Generated by biocroxytest: do not edit by hand!",
#'   file.path(pkg, "tests", "testthat", "test-roxytest-tests-example.R")
#' )
#' generated_test_inventory(pkg)
#' unlink(pkg, recursive = TRUE)
generated_test_inventory <- function(path = ".") {
  path <- test_package_path(path)
  collect_test_inventory(path)
}

#' @rdname generated_test_inventory
#' @export
check_generated_tests <- function(path = ".") {
  path <- test_package_path(path)
  copy <- test_package_copy_path(path)
  on.exit(unlink(copy, recursive = TRUE, expand = FALSE), add = TRUE)
  copy_test_package(path, copy)

  before <- collect_test_inventory(copy)
  contents <- stats::setNames(lapply(file.path(copy, before$path), read_test_bytes), before$path)
  suites <- regenerate_test_copy(copy)
  if (!length(suites)) {
    cli::cli_abort(c(
      "No biocroxytest test roclet is configured.",
      i = "Configure {.code biocroxytest::tests_roclet} or {.code biocroxytest::longtests_roclet}."
    ), class = "biocroxytest_test_check_input", call = NULL)
  }
  before <- before[before$suite %in% suites, , drop = FALSE]
  after <- collect_test_inventory(copy, suites)
  changes <- compare_test_inventory(before, after, contents, copy)
  if (nrow(changes)) { abort_stale_tests(changes) }
  invisible(TRUE)
}

test_package_copy_path <- function(path) {
  copy <- tempfile("biocroxytest-", tmpdir = fs::path_real(tempdir()))
  relative <- fs::path_rel(copy, start = path)
  if (!startsWith(relative, "../") && !fs::is_absolute_path(relative)) {
    cli::cli_abort("The temporary directory must be outside the package.",
                   class = "biocroxytest_test_check_input", call = NULL)
  }
  copy
}

test_package_path <- function(path) {
  if (!is.character(path) || length(path) != 1L || is.na(path) ||
      !dir.exists(path) || !file.exists(file.path(path, "DESCRIPTION")) ||
      dir.exists(file.path(path, "DESCRIPTION"))) {
    cli::cli_abort("Supply a package directory containing a {.file DESCRIPTION} file.",
                   class = "biocroxytest_test_check_input", call = NULL)
  }
  fs::path_real(path)
}

collect_test_inventory <- function(path, suites = c("tests", "longtests")) {
  rows <- lapply(suites, function(suite) {
    directory <- file.path(suite, "testthat")
    dirs <- file.path(path, c(suite, directory))
    if (!all(fs::file_info(dirs, fail = FALSE)$type %in% "directory")) {
      return(NULL)
    }
    files <- fs::dir_ls(dirs[2L], type = "file")
    files <- files[vapply(files, function(file) {
      kind <- if (suite == "tests" && startsWith(basename(file), example_test_prefix)) {
        "testexamples"
      } else {
        suite
      }
      made_by_biocroxytest(file, kind)
    }, logical(1))]
    names <- sort(basename(files), method = "radix")
    source <- substring(names, nchar(test_prefix(suite)) + 1L)
    example <- suite == "tests" & startsWith(names, example_test_prefix)
    source[example] <- substring(names[example], nchar(example_test_prefix) + 1L)
    # Early long-test versions were also allowed to use the shorter ownership prefix.
    legacy <- suite == "longtests" & !startsWith(names, test_prefix(suite))
    source[legacy] <- substring(names[legacy], nchar("test-biocroxytest-") + 1L)
    data.frame(
      suite = rep(suite, length(names)),
      source = paste0("R/", source, recycle0 = TRUE),
      path = paste0(directory, "/", names, recycle0 = TRUE)
    )
  })
  do.call(rbind, c(list(data.frame(suite = character(), source = character(),
                                   path = character())), rows))
}

copy_test_package <- function(from, to) {
  fs::dir_create(to)
  entries <- fs::dir_ls(from, all = TRUE)
  entries <- entries[basename(entries) != ".git"]
  types <- fs::file_info(entries)$type
  unsupported <- which(!types %in% c("file", "directory"))
  if (length(unsupported)) {
    entry <- entries[unsupported[1L]]
    cli::cli_abort(c(
      "Cannot copy linked or special file {.file {entry}}.",
      i = "Run the check from a checkout with ordinary files and directories."
    ), class = "biocroxytest_test_check_input", call = NULL)
  }
  files <- entries[types == "file"]
  fs::file_copy(files, file.path(to, basename(files)))
  for (directory in entries[types == "directory"]) {
    copy_test_package(directory, file.path(to, basename(directory)))
  }
}

regenerate_test_copy <- function(copy) {
  generator <- getNamespaceInfo(asNamespace("biocroxytest"), "path")
  installed <- file.exists(file.path(generator, "Meta", "package.rds"))
  tryCatch(
    callr::r(function(path, generator, installed) {
      setwd(path)
      if (installed) {
        loadNamespace("biocroxytest", lib.loc = dirname(generator))
      } else {
        roxygen2::load_pkgload(generator)
      }
      recorded <- new.env(parent = emptyenv())
      recorded$suites <- character()
      options(biocroxytest.record_test_suites = function(current) {
        recorded$suites <- union(recorded$suites, current)
      })
      roxygen2::roxygenise()
      recorded$suites
    }, args = list(copy, generator, installed), user_profile = FALSE, system_profile = FALSE,
    error = "error", stderr = "2>&1", show = TRUE, spinner = FALSE),
    error = function(e) {
      cli::cli_abort(c(
        "Could not regenerate tests in the temporary package copy.",
        i = "Run {.code roxygen2::roxygenise()} to diagnose the generation error."
      ), class = "biocroxytest_test_regeneration_error", parent = e, call = NULL)
    }
  )
}

read_test_bytes <- function(path) {
  bytes <- readBin(path, "raw", n = file.size(path))
  cr <- which(bytes == as.raw(13L))
  cr <- cr[cr < length(bytes)]
  crlf <- cr[bytes[cr + 1L] == as.raw(10L)]
  if (length(crlf)) bytes[-crlf] else bytes
}

compare_test_inventory <- function(before, after, contents, copy) {
  missing <- !after$path %in% before$path
  obsolete <- !before$path %in% after$path
  common <- after[!missing, , drop = FALSE]
  changed <- vapply(common$path, function(path) {
    !identical(contents[[path]], read_test_bytes(file.path(copy, path)))
  }, logical(1))
  rows <- rbind(after[missing, ], common[changed, ], before[obsolete, ])
  status <- rep(c("missing", "changed", "obsolete"), c(sum(missing), sum(changed), sum(obsolete)))
  data.frame(status, rows, row.names = NULL)
}

abort_stale_tests <- function(changes) {
  bullets <- vapply(seq_len(nrow(changes)), function(i) {
    paste0("{changes$status[", i, "]} {.file {encodeString(changes$path[", i, "])}}")
  }, character(1))
  names(bullets) <- rep("*", length(bullets))
  cli::cli_abort(c(
    "Generated tests are out of date.", bullets,
    i = "Run {.code roxygen2::roxygenise()} and commit the generated test changes."
  ), class = "biocroxytest_stale_tests", changes = changes, call = NULL)
}
