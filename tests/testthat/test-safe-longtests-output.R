test_that("roxygenise validates every generated file before changing longtests", {
  pkg <- tempfile("longtests-package-")
  on.exit(unlink(pkg, recursive = TRUE), add = TRUE)
  dir.create(file.path(pkg, "R"), recursive = TRUE)
  dest <- file.path(pkg, "longtests", "testthat")
  dir.create(dest, recursive = TRUE)
  writeLines(
    c("Package: safelongtestfixture", "Version: 0.0.1", "Encoding: UTF-8"),
    file.path(pkg, "DESCRIPTION")
  )
  writeLines(character(), file.path(pkg, "NAMESPACE"))
  header <- "# Generated by biocroxytest: do not edit by hand!"
  paths <- file.path(dest, paste0("test-biocroxytest-longtests-", c(
    "a.R", "b.R", "stale.R", "manual-lower.r", "manual-upper.R"
  )))
  for (path in paths[1:3]) writeLines(c(header, "old_test <- TRUE"), path)
  writeLines("# Manual lowercase test", paths[4])
  writeLines("# Manual uppercase test", paths[5])
  contents <- function(files) {
    lapply(files, function(file) if (file.exists(file)) readLines(file) else NULL)
  }
  output_state <- function() {
    files <- list.files(dest, all.files = TRUE, no.. = TRUE)
    setNames(lapply(files, function(name) {
      file <- file.path(dest, name)
      readBin(file, "raw", n = file.size(file))
    }), files)
  }
  before <- contents(paths)
  expected_state <- output_state()

  writeLines(
    c("#' @longtests expect_true(TRUE)", "a <- function() TRUE"),
    file.path(pkg, "R", "a.R")
  )
  writeLines(
    c("#' @longtests expect_true(", "b <- function() TRUE"),
    file.path(pkg, "R", "b.R")
  )

  generate <- function(clean) {
    roxygenise_fixture(pkg, roclets = "biocroxytest::longtests_roclet", clean = clean)
  }
  for (clean in c(FALSE, TRUE)) {
    expect_error(generate(clean), "b[.]R")
    expect_identical(output_state(), expected_state)
    for (i in seq_along(paths)) writeLines(before[[i]], paths[i])
  }

  writeLines(
    c("#' @longtests expect_false(FALSE)", "b <- function() TRUE"),
    file.path(pkg, "R", "b.R")
  )
  unlink(paths[2])
  for (name in c("b.R", "b.r")) {
    collision <- file.path(dest, paste0("test-biocroxytest-longtests-", name))
    writeLines("# Manual test at a generated destination", collision)
    preserved <- c(paths[-2], collision)
    before <- contents(preserved)
    expected_state <- output_state()
    for (clean in c(FALSE, TRUE)) {
      expect_error(generate(clean), "collides.*b[.]R")
      expect_identical(output_state(), expected_state)
      for (i in seq_along(preserved)) writeLines(before[[i]], preserved[i])
    }
    unlink(collision)
  }

  manual <- contents(paths[4:5])
  generate(TRUE)
  expect_true(all(file.exists(paths[-3])))
  expect_false(file.exists(paths[3]))
  expect_identical(contents(paths[4:5]), manual)
  expect_length(parse(paths[1]), 1L)
  expect_length(parse(paths[2]), 1L)
  after <- lapply(paths[-3], readLines)
  generate(FALSE)
  expect_identical(lapply(paths[-3], readLines), after)

  # A source basename can fit even when its generated basename does not.
  long_name <- paste0(strrep("z", 238L), ".R")
  probe <- file.path(dest, paste0("test-biocroxytest-longtests-", long_name))
  if (!suppressWarnings(file.create(probe))) {
    source <- file.path(pkg, "R", long_name)
    if (suppressWarnings(file.create(source))) {
      writeLines(c("#' @longtests expect_true(TRUE)", "z <- function() TRUE"), source)
      writeLines(c(header, "old_test <- TRUE"), paths[1])
      expected_state <- output_state()
      expect_error(suppressWarnings(generate(TRUE)), "Could not stage")
      expect_identical(output_state(), expected_state)
    }
  } else {
    unlink(probe)
  }
})

test_that("Unicode filename aliases cannot replace or remove an existing test", {
  pkg <- tempfile("longtests-package-")
  on.exit(unlink(pkg, recursive = TRUE), add = TRUE)
  dir.create(file.path(pkg, "R"), recursive = TRUE)
  dest <- file.path(pkg, "longtests", "testthat")
  dir.create(dest, recursive = TRUE)
  writeLines(
    c("Package: aliaslongtestfixture", "Version: 0.0.1", "Encoding: UTF-8"),
    file.path(pkg, "DESCRIPTION")
  )
  writeLines(character(), file.path(pkg, "NAMESPACE"))

  old <- file.path(dest, "test-biocroxytest-longtests-cafe\u0301.R")
  new <- file.path(dest, "test-biocroxytest-longtests-caf\u00e9.R")
  writeLines(c("# Generated by biocroxytest: do not edit by hand!", "old_test <- TRUE"), old)
  if (!file.exists(new) || identical(basename(new), list.files(dest))) {
    skip("This filesystem does not expose the two Unicode spellings as aliases")
  }
  before <- readLines(old)
  writeLines(
    c("#' @longtests expect_true(TRUE)", "f <- function() TRUE"),
    file.path(pkg, "R", "caf\u00e9.R")
  )
  expect_error(
    roxygenise_fixture(pkg, roclets = "biocroxytest::longtests_roclet", clean = TRUE),
    "collides"
  )
  expect_identical(list.files(dest, all.files = TRUE, no.. = TRUE), basename(old))
  expect_identical(readLines(old), before)
})
